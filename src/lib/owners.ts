const displayNames = new Map<string, Intl.DisplayNames | null>()

/** Localised country name for a SATCAT owner code; organisations and joint owners keep their English name. */
export function ownerName(code: string, lang: string): string {
  const entry = OWNER_NAMES[code]
  if (!entry) return code
  const [iso, en] = entry
  if (!iso || lang === 'en') return en
  if (!displayNames.has(lang)) {
    try {
      displayNames.set(lang, new Intl.DisplayNames([lang], { type: 'region' }))
    } catch {
      displayNames.set(lang, null)
    }
  }
  return displayNames.get(lang)?.of(iso) ?? en
}
